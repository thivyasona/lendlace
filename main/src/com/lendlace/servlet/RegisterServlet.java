package com.lendlace.servlet;

import com.lendlace.dao.UserDAO;
import com.lendlace.model.User;
import com.lendlace.util.PasswordUtil;

import java.io.File;
import java.io.IOException;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.MultipartConfig;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.Part;

@MultipartConfig(maxFileSize = 2 * 1024 * 1024)
@WebServlet("/register")
public class RegisterServlet extends HttpServlet {

    @Override
    protected void doPost(HttpServletRequest request,
                          HttpServletResponse response)
            throws ServletException, IOException {

        String fullName = request.getParameter("fullName") == null ? ""
                : request.getParameter("fullName").trim();
        String email = request.getParameter("email") == null
                ? "" : request.getParameter("email").trim().toLowerCase();
        // trim CR/LF: some clients append the boundary line break to the last field value
        String password = trimCRLF(request.getParameter("password"));
        String confirmPassword = trimCRLF(request.getParameter("confirmPassword"));
        String roleParam = request.getParameter("role"); // advisory only, never trusted for the role

        // --- server-side validation ---
        if (fullName.isEmpty()
                || email.isEmpty() || !email.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$")) {
            response.sendRedirect("register.jsp?error=1");
            return;
        }
        if (password == null || password.length() < 8) {
            response.sendRedirect("register.jsp?error=weak");
            return;
        }
        if (confirmPassword != null && !confirmPassword.isEmpty()
                && !password.equals(confirmPassword)) {
            response.sendRedirect("register.jsp?error=mismatch");
            return;
        }

        // --- SECURITY: the role is decided by the server, never by the form. ---
        // Public registration may only create CUSTOMER or OWNER accounts.
        // ADMIN exists only via the trusted provisioning script (database/setup-admin.sql).
        String role = "OWNER".equalsIgnoreCase(roleParam) ? "OWNER" : "CUSTOMER";

        User user = new User();
        user.setFullName(fullName);
        user.setEmail(email);
        user.setPassword(PasswordUtil.hash(password)); // never store plaintext
        user.setPhone(request.getParameter("phone"));
        user.setRole(role);

        // combine address fields into one address column
        String address = request.getParameter("address");
        String city = request.getParameter("city");
        String state = request.getParameter("state");
        String pincode = request.getParameter("pincode");
        StringBuilder fullAddress = new StringBuilder();
        if (address != null && !address.trim().isEmpty()) fullAddress.append(address.trim());
        if (city != null && !city.trim().isEmpty()) fullAddress.append(", ").append(city.trim());
        if (state != null && !state.trim().isEmpty()) fullAddress.append(", ").append(state.trim());
        if (pincode != null && !pincode.trim().isEmpty()) fullAddress.append(" - ").append(pincode.trim());
        user.setAddress(fullAddress.toString());

        user.setRole(role); // server-decided; ADMIN can never be injected here

        // save the uploaded profile image, fall back to default
        String imagePath = "assets/images/default-user.png";
        try {
            Part imagePart = request.getPart("profileImage");
            if (imagePart != null && imagePart.getSubmittedFileName() != null
                    && !imagePart.getSubmittedFileName().isEmpty()
                    && imagePart.getSize() > 0
                    && isAllowedImage(imagePart.getContentType(),
                            imagePart.getSubmittedFileName())) {
                // persistent upload dir outside the webapp (survives redeploys)
                String override = System.getProperty("UPLOAD_DIR");
                File uploadDir = (override != null && !override.isEmpty())
                        ? new File(override)
                        : new File(System.getProperty("catalina.base",
                                getServletContext().getRealPath("")), "lendlace-uploads");
                if (!uploadDir.exists()) uploadDir.mkdirs();
                // unique, safe name generated by the server (prevents path traversal / overwrites)
                String safeName = "user_" + System.currentTimeMillis() + "_"
                        + safeName(imagePart.getSubmittedFileName());
                File dest = new File(uploadDir, safeName);
                imagePart.write(dest.getAbsolutePath());
                imagePath = "uploads/" + dest.getName();
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
        user.setProfileImage(imagePath);

        UserDAO dao = new UserDAO();

        // enforce unique email
        if (user.getEmail() == null || user.getEmail().trim().isEmpty()
                || dao.emailExists(user.getEmail().trim())) {
            response.sendRedirect("register.jsp?error=email");
            return;
        }

        if (dao.register(user)) {
            response.sendRedirect("login.jsp?success=1");
        } else {
            response.sendRedirect("register.jsp?error=1");
        }
    }

    /** Strips trailing CR/LF characters that some multipart clients append. */
    static String trimCRLF(String s) {
        if (s == null) return null;
        return s.replaceAll("[\\r\\n]+$", "");
    }

    /** Only real image MIME types and extensions are accepted. */
    static boolean isAllowedImage(String contentType, String fileName) {
        if (contentType == null) return false;
        String ok = "image/jpeg,image/png,image/gif,image/webp";
        boolean typeOk = ok.contains(contentType.toLowerCase());
        String name = fileName == null ? "" : fileName.toLowerCase();
        boolean extOk = name.endsWith(".jpg") || name.endsWith(".jpeg")
                || name.endsWith(".png") || name.endsWith(".gif") || name.endsWith(".webp");
        return typeOk && extOk;
    }

    /** Safe filename: strips path components and dangerous characters (prevents path traversal). */
    static String safeName(String submitted) {
        String name = submitted == null ? "file" : submitted;
        name = name.replace('\\', '/');
        int slash = name.lastIndexOf('/');
        if (slash >= 0) name = name.substring(slash + 1);
        name = name.replaceAll("[^A-Za-z0-9._-]", "_");
        if (name.isEmpty() || name.equals(".") || name.equals("..")) name = "file";
        return name;
    }
}